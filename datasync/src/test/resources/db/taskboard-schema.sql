-- Verbatim copy of the Taskboard schema from the shared system contract. The backend owns the
-- schema and applies it with Flyway; the datasync never migrates the shared database. The tests
-- create this copy in their own embedded H2 (MODE=DB2).
CREATE TABLE TASK (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE       VARCHAR(40)   NOT NULL,
    DESCRIPTION VARCHAR(200),
    STATUS      VARCHAR(20)   NOT NULL,
    ASSIGNEE    VARCHAR(8),
    DUE_DATE    DATE,
    SOURCE      VARCHAR(10)   NOT NULL,
    HOST_ID     VARCHAR(10),
    CREATED_AT  TIMESTAMP     NOT NULL,
    UPDATED_AT  TIMESTAMP     NOT NULL
);
CREATE INDEX IX_TASK_HOST_ID ON TASK (HOST_ID);

CREATE TABLE OUTBOX_EVENT (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGGREGATE_TYPE VARCHAR(30)   NOT NULL,
    AGGREGATE_ID   BIGINT        NOT NULL,
    EVENT_TYPE     VARCHAR(30)   NOT NULL,
    PAYLOAD        VARCHAR(4000) NOT NULL,
    STATUS         VARCHAR(20)   DEFAULT 'PENDING' NOT NULL,
    ATTEMPTS       INTEGER       DEFAULT 0 NOT NULL,
    LAST_ERROR     VARCHAR(1000),
    CREATED_AT     TIMESTAMP     NOT NULL,
    PROCESSED_AT   TIMESTAMP
);
CREATE INDEX IX_OUTBOX_EVENT_STATUS ON OUTBOX_EVENT (STATUS, ID);
CREATE INDEX IX_OUTBOX_EVENT_AGGREGATE ON OUTBOX_EVENT (AGGREGATE_ID, ID);
